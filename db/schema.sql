
-- Удаление таблиц только для учебного пересоздания БД
DROP TABLE IF EXISTS trips CASCADE;
DROP TABLE IF EXISTS carriages CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- Справочник типов вагонов
CREATE TABLE carriages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    type varchar(20) NOT NULL
);

-- Пользователи системы
CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(50) NOT NULL,
    full_name varchar(200) NOT NULL,
    role varchar(20) NOT NULL,
    CONSTRAINT "CK_users_role"
        CHECK (role IN ('passenger', 'conductor', 'admin'))
);

-- Главный объект — поездки
CREATE TABLE trips (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number varchar(20) NOT NULL,
    title varchar(80) NOT NULL,
    description varchar(500) NOT NULL,
    status varchar(20) NOT NULL,
    carriage_id integer NOT NULL REFERENCES carriages(id),
    created_by_user_id integer NOT NULL REFERENCES users(id),
    assignee_user_id integer NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT "CK_trips_status"
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled'))
);

-- Уникальные индексы
CREATE UNIQUE INDEX "IX_users_login" ON users (login);
CREATE UNIQUE INDEX "IX_trips_number" ON trips (number);

-- Индексы внешних ключей
CREATE INDEX "IX_trips_assignee_user_id"
    ON trips (assignee_user_id);

CREATE INDEX "IX_trips_carriage_id"
    ON trips (carriage_id);

CREATE INDEX "IX_trips_created_by_user_id"
    ON trips (created_by_user_id);

-- Индексы для фильтрации и сортировки
CREATE INDEX "IX_trips_status"
    ON trips (status);

CREATE INDEX "IX_trips_created_at"
    ON trips (created_at DESC);
