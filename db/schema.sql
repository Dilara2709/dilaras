
-- Удаляем старые таблицы
-- Только для учебного пересоздания базы данных!
DROP TABLE IF EXISTS trips CASCADE;
DROP TABLE IF EXISTS carriages CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- Справочник типов вагонов
CREATE TABLE carriages (
  id    integer PRIMARY KEY,
  name  varchar(50) NOT NULL,
  type  varchar(20) NOT NULL
);

-- Пользователи системы
CREATE TABLE users (
  id        integer PRIMARY KEY,
  login     varchar(50) NOT NULL UNIQUE,
  full_name varchar(200) NOT NULL,
  role      varchar(20) NOT NULL
            CHECK (role IN ('passenger', 'conductor', 'admin'))
);

-- Главный объект — поездки
CREATE TABLE trips (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number             text NOT NULL UNIQUE,
  title              varchar(80) NOT NULL,
  description        varchar(500) NOT NULL,
  carriage_id        integer NOT NULL REFERENCES carriages (id),
  status             varchar(20) NOT NULL
                     CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
  created_at         timestamptz NOT NULL DEFAULT now(),
  created_by_user_id integer NOT NULL REFERENCES users (id),
  assignee_user_id   integer NULL REFERENCES users (id)
);

-- Индекс для фильтрации поездок по статусу
CREATE INDEX trips_status_idx ON trips (status);

-- Индекс для фильтрации поездок по типу вагона
CREATE INDEX trips_carriage_id_idx ON trips (carriage_id);

-- Индекс для сортировки поездок по дате создания
CREATE INDEX trips_created_at_idx ON trips (created_at DESC);
